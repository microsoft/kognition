const helmGuard = `{{- if and (eq .Values.mode "kubernetes") .Values.rbac.humanRoles.enabled }}`

func renderOrFail(t *testing.T) []byte {
	t.Helper()
	out, err := Default().RenderChartTemplate()
	if err != nil {
		t.Fatalf("RenderChartTemplate: %v", err)
	}
	return out
}

// plainYAML removes Helm directive lines so the rendered body can be parsed.
func plainYAML(template string) []string {
	var kept []string
	for _, line := range strings.Split(template, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "{{") {
			continue
		}
		kept = append(kept, line)
	}
	var documents []string
	var current []string
	flush := func() {
		if text := strings.TrimSpace(strings.Join(current, "\n")); text != "" && !allComments(text) {
			documents = append(documents, text)
		}
		current = nil
	}
	for _, line := range kept {
		if strings.TrimSpace(line) == "---" {
			flush()
			continue
		}
		current = append(current, line)
	}
	flush()
	return documents
}

func allComments(text string) bool {
	for _, line := range strings.Split(text, "\n") {
		if trimmed := strings.TrimSpace(line); trimmed != "" && !strings.HasPrefix(trimmed, "#") {
			return false
		}
	}
	return true
}

func TestRenderChartTemplateIsDeterministic(t *testing.T) {
	first := renderOrFail(t)
	second := renderOrFail(t)
	if !bytes.Equal(first, second) {
		t.Fatal("two renders of the same catalog differ")
	}
	if len(first) == 0 {
		t.Fatal("render produced no output")
	}
}

func TestRenderChartTemplateStructure(t *testing.T) {
	out := string(renderOrFail(t))
	if !strings.HasPrefix(out, "# Copyright (c) Microsoft Corporation.\n# Licensed under the MIT License.\n") {
		t.Error("the template must start with the repository license header")
	}
	if !strings.Contains(out, "Code generated by tools/access-catalog; DO NOT EDIT.") {
		t.Error("the template must say it is generated")
	}
	if strings.Count(out, helmGuard) != 1 {
		t.Errorf("the template must be guarded exactly once by %s", helmGuard)
	}
	if !strings.HasSuffix(out, "{{- end }}\n") {
		t.Error("the template must end by closing the guard with a trailing newline")
	}
	if strings.Contains(out, "\r") {
		t.Error("the template must use LF line endings")
	}
	for _, forbidden := range []string{"kind: RoleBinding", "kind: ClusterRoleBinding", "aggregate-to-", "aggregationRule", "subjects:"} {
		if strings.Contains(out, forbidden) {
			t.Errorf("roles must be inert; found %q", forbidden)
		}
	}
}

func TestRenderedRolesMatchTheCatalog(t *testing.T) {
	catalog := Default()
	want, err := catalog.ClusterRoles()
	if err != nil {
		t.Fatal(err)
	}
	documents := plainYAML(string(renderOrFail(t)))
	if len(documents) != len(want) {
		t.Fatalf("rendered %d roles, catalog has %d", len(documents), len(want))
	}
	for i, document := range documents {
		var got rbacv1.ClusterRole
		if err := yaml.UnmarshalStrict([]byte(document), &got); err != nil {
			t.Fatalf("role %d is not a valid ClusterRole: %v\n%s", i, err, document)
		}
		if got.APIVersion != "rbac.authorization.k8s.io/v1" || got.Kind != "ClusterRole" {
			t.Errorf("role %d is %s %s", i, got.APIVersion, got.Kind)
		}
		if got.Name != want[i].Name {
			t.Errorf("role %d is %q, want %q (catalog order)", i, got.Name, want[i].Name)
		}
		if got.Labels[RoleLabel] != want[i].Labels[RoleLabel] {
			t.Errorf("%s label = %q, want %q", got.Name, got.Labels[RoleLabel], want[i].Labels[RoleLabel])
		}
		if !reflect.DeepEqual(got.Rules, want[i].Rules) {
			t.Errorf("%s rendered rules differ from the catalog:\n got %+v\nwant %+v", got.Name, got.Rules, want[i].Rules)
		}
	}
}

func TestRenderedTemplateUsesTheChartLabelsHelper(t *testing.T) {
	out := string(renderOrFail(t))
	if got, want := strings.Count(out, `{{- include "kognition.labels" . | nindent 4 }}`), len(Default().Roles); got != want {
		t.Errorf("chart labels helper used %d times, want once per role (%d)", got, want)
	}
}
