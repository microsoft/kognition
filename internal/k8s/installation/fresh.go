// FreshWorkloadsEmpty refuses recovery once user workloads or non-bootstrap resources exist.
func (operations *Kubernetes) FreshWorkloadsEmpty(ctx context.Context, content []byte, probes []activation.ResourceIntent, transactionUID string, includeInstallation bool) error {
	bootstrap, err := Documents(content)
	if err != nil {
		return err
	}
	allowed := map[string]bool{}
	for _, object := range bootstrap {
		allowed[releaseIdentity(object.GetAPIVersion(), object.GetKind(), object.GetNamespace(), object.GetName())] = true
	}
	ownedProbe := func(object *unstructured.Unstructured) bool {
		if transactionUID == "" || object.GetUID() == "" || object.GetAnnotations()["kognition.dev/activation-transaction"] != transactionUID {
			return false
		}
		for _, intent := range probes {
			if intent.Probe && !intent.Rejected && intent.APIVersion == object.GetAPIVersion() && intent.Kind == object.GetKind() &&
				intent.Namespace == object.GetNamespace() && intent.Name == object.GetName() &&
				(intent.UID == "" || intent.UID == string(object.GetUID())) {
				return true
			}
		}
		return false
	}
	groups, err := operations.Discovery.ServerPreferredResources()
	if err != nil {
		return err
	}
	for _, group := range groups {
		version, err := schema.ParseGroupVersion(group.GroupVersion)
		if err != nil {
			return err
		}
		if !strings.Contains(version.Group, "kognition") {
			continue
		}
		for _, resource := range group.APIResources {
			if strings.Contains(resource.Name, "/") || !slices.Contains(resource.Verbs, "list") {
				continue
			}
			objects := &unstructured.UnstructuredList{}
			objects.SetGroupVersionKind(version.WithKind(resource.Kind + "List"))
			if err := operations.Admin.List(ctx, objects); err != nil {
				return err
			}
			for _, object := range objects.Items {
				if object.GetNamespace() != "" && object.GetNamespace() != operations.Manifest.Namespace && !slices.Contains(operations.Manifest.Namespaces, object.GetNamespace()) {
					continue
				}
				if !allowed[releaseIdentity(object.GetAPIVersion(), object.GetKind(), object.GetNamespace(), object.GetName())] && !ownedProbe(&object) {
					return fmt.Errorf("fresh recovery cannot stop an installation with user resources; drain/finalize or migrate %s %s/%s first", resource.Kind, object.GetNamespace(), object.GetName())
				}
			}
		}
	}
	namespaces := operations.Manifest.Namespaces
	if includeInstallation {
		namespaces = append([]string{operations.Manifest.Namespace}, namespaces...)
	}
	for _, namespace := range namespaces {
		for _, kind := range []schema.GroupVersionKind{
			{Version: "v1", Kind: "PodList"}, {Version: "v1", Kind: "ReplicationControllerList"},
			{Group: "apps", Version: "v1", Kind: "DeploymentList"}, {Group: "apps", Version: "v1", Kind: "ReplicaSetList"},
			{Group: "apps", Version: "v1", Kind: "StatefulSetList"}, {Group: "apps", Version: "v1", Kind: "DaemonSetList"},
			{Group: "batch", Version: "v1", Kind: "JobList"}, {Group: "batch", Version: "v1", Kind: "CronJobList"},
		} {
			objects := &unstructured.UnstructuredList{}
			objects.SetGroupVersionKind(kind)
			if err := operations.Admin.List(ctx, objects, client.InNamespace(namespace)); err != nil {
				return err
			}
			for _, object := range objects.Items {
				if !ownedProbe(&object) {
					return errors.New("fresh recovery requires empty workload namespaces; use the existing-release drain workflow")
				}
			}
		}
	}
	return nil
}

func ValidateFreshPlan(plan Plan) error {
	if plan.Version != 1 || plan.ReleaseRevision != 0 || plan.PreviousManifest != nil || plan.FailedRelease != nil ||
		plan.PreviousDeployedManifest != nil || plan.PreviousDeployedRevision != 0 ||
		len(plan.Controllers)+len(plan.Grants)+len(plan.LegacyPolicies)+len(plan.RetainedObjects)+len(plan.CompletedMigrationJobs)+len(plan.CleanupAttestations)+len(plan.AbsentObjects) != 0 {
		return errors.New("fresh installation requires revision zero and no previous release, cleanup or retained-resource inventory; use the upgrade/recovery workflow for an existing installation")
	}
	return nil
}

// FreshRender freezes credentials generated by the first render; all other fields remain exact.
func FreshRender(expected, actual []byte, release string) ([]byte, error) {
	reviewed, err := Documents(expected)
	if err != nil {
		return nil, err
	}
	rendered, err := Documents(actual)
	if err != nil {
		return nil, err
	}
	secrets := map[string]*unstructured.Unstructured{}
	for _, object := range reviewed {
		if object.GetAPIVersion() == "v1" && object.GetKind() == "Secret" {
			secrets[object.GetNamespace()+"/"+object.GetName()] = object
		}
	}
	var result bytes.Buffer
	for _, object := range rendered {
		if object.GetAPIVersion() == "v1" && object.GetKind() == "Secret" {
			if original := secrets[object.GetNamespace()+"/"+object.GetName()]; original != nil {
				for _, field := range []string{"data", "stringData"} {
					if value, found := original.Object[field]; found {
						object.Object[field] = value
					} else {
						delete(object.Object, field)
					}
				}
			}
		}
		content, err := json.Marshal(object.Object)
		if err != nil {
			return nil, err
		}
		result.Write(content)
		result.WriteString("\n---\n")
	}
	if _, err := ValidateRender(expected, result.Bytes(), release); err != nil {
		return nil, err
	}
	return result.Bytes(), nil
}

func (journal *Journal) AuthorizeFresh(ctx context.Context, plan Plan, target activation.ActivationTarget) (*corev1.ConfigMap, error) {
	if err := ValidateFreshPlan(plan); err != nil {
		return nil, err
	}
	if target.ClusterUID != plan.ClusterUID || target.Release != plan.Release || target.Endpoint != plan.Endpoint ||
		target.AuthorityNamespace != plan.AuthorityNamespace || target.ManifestSHA256 != plan.Manifest.SHA256 || target.ChartSHA256 != plan.Chart.SHA256 {
		return nil, errors.New("fresh activation target differs from the installation plan")
	}
	live := &corev1.ConfigMap{}
	if err := journal.admin.Get(ctx, client.ObjectKeyFromObject(journal.record), live); err != nil {
		return nil, err
	}
	if live.UID != journal.record.UID || live.ResourceVersion != journal.record.ResourceVersion || !reflect.DeepEqual(live.Data, journal.record.Data) ||
		live.Data["mode"] != "fresh" || live.Data["clusterUID"] != plan.ClusterUID || live.Data["namespaceUID"] != plan.NamespaceUID || live.Data["release"] != plan.Release ||
		!validHistory(live.Data["events"]) || !strings.HasSuffix(live.Data["events"], "\nverified-inactive\n") {
		return nil, errors.New("fresh bootstrap claim is incomplete or changed")
	}
	namespaces := map[string]string{
		"kube-system": plan.ClusterUID, target.Namespace: plan.NamespaceUID,
		plan.AuthorityNamespace: plan.AuthorityNamespaceUID,
	}
	for name, uid := range plan.WorkloadNamespaceUIDs {
		namespaces[name] = uid
	}
	bound := map[string]string{}
	for _, object := range target.Objects {
		if object.APIVersion == "v1" && object.Kind == "Namespace" {
			bound[object.Name] = object.UID
		}
	}
	if !reflect.DeepEqual(bound, namespaces) {
		return nil, errors.New("fresh authorization namespace inventory differs from the installation plan")
	}
	now := time.Now().UTC()
	approval := activation.Approval{
		Version: activation.FreshApprovalVersion, Approver: "kognition-install/fresh",
		IssuedAt: now, ExpiresAt: now.Add(activation.ApprovalLifetime), Target: target,
	}
	if err := activation.ValidateFreshAuthorization(approval, target, now); err != nil {
		return nil, err
	}
	encoded, err := json.Marshal(approval)
	if err != nil {
		return nil, err
	}
	proof, err := json.Marshal(activation.FreshBootstrapEvidence{
		Version: activation.FreshApprovalVersion, ClaimName: live.Name, ClaimUID: string(live.UID),
		PlanSHA256: live.Data["planSHA256"], NamespaceUIDs: namespaces,
	})
	if err != nil {
		return nil, err
	}
	digest := sha256.Sum256([]byte(live.UID))
	record := &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{Name: fmt.Sprintf("fresh-install-%x", digest[:16]), Namespace: plan.AuthorityNamespace},
		Immutable:  ptr.To(true),
		Data:       map[string]string{"approval.json": string(encoded), "fresh-bootstrap.json": string(proof)},
	}
	if err := journal.admin.Create(ctx, record); err != nil {
		return nil, fmt.Errorf("fresh authorization was not created; preserve the installation state before retrying: %w", err)
	}
	if record.UID == "" || record.ResourceVersion == "" {
		return nil, errors.New("fresh authorization lacks a persisted server identity")
	}
	return record, nil
}

// WaitForFreshServices completes migrations and non-controller rollouts before granting controller access.
func WaitForFreshServices(ctx context.Context, admin client.Client, content []byte) error {
	objects, err := Documents(content)
	if err != nil {
		return err
	}
	var pending error
	err = wait.PollUntilContextTimeout(ctx, time.Second, 5*time.Minute, true, func(ctx context.Context) (bool, error) {
		for _, expected := range objects {
			if expected.GetAPIVersion() != "apps/v1" && expected.GetAPIVersion() != "batch/v1" {
				continue
			}
			kind := expected.GetKind()
			if kind != "Deployment" && kind != "StatefulSet" && kind != "Job" {
				continue
			}
			component, _, _ := unstructured.NestedString(expected.Object, "spec", "template", "metadata", "labels", "app.kubernetes.io/component")
			if kind == "Deployment" && component == "k8s-controller" {
				continue
			}
			live := &unstructured.Unstructured{}
			live.SetGroupVersionKind(expected.GroupVersionKind())
			if err := admin.Get(ctx, client.ObjectKeyFromObject(expected), live); err != nil {
				if apierrors.IsNotFound(err) {
					pending = fmt.Errorf("waiting for %s %s/%s", kind, expected.GetNamespace(), expected.GetName())
					return false, nil
				}
				return false, err
			}
			pending = fmt.Errorf("waiting for %s %s/%s readiness", kind, live.GetNamespace(), live.GetName())
			if live.GetUID() == "" || live.GetDeletionTimestamp() != nil {
				return false, errors.New("fresh installation service has no UID or is being deleted")
			}
			if kind == "Job" {
				conditions, _, err := unstructured.NestedSlice(live.Object, "status", "conditions")
				if err != nil {
					return false, err
				}
				complete := false
				for _, value := range conditions {
					condition, ok := value.(map[string]interface{})
					if !ok {
						return false, errors.New("invalid migration Job condition")
					}
					if condition["type"] == "Failed" && condition["status"] == "True" {
						return false, fmt.Errorf("migration Job failed: %s/%s", live.GetNamespace(), live.GetName())
					}
					complete = complete || condition["type"] == "Complete" && condition["status"] == "True"
				}
				if !complete {
					return false, nil
				}
				continue
			}
			replicas, found, err := unstructured.NestedInt64(expected.Object, "spec", "replicas")
			if err != nil {
				return false, err
			}
			if !found {
				replicas = 1
			}
			actual, found, err := unstructured.NestedInt64(live.Object, "spec", "replicas")
			if err != nil || !found || actual != replicas {
				return false, errors.New("service replica configuration changed during fresh installation")
			}
			observed, _, err := unstructured.NestedInt64(live.Object, "status", "observedGeneration")
			if err != nil {
				return false, err
			}
			ready, _, err := unstructured.NestedInt64(live.Object, "status", "readyReplicas")
			if err != nil {
				return false, err
			}
			updated, _, err := unstructured.NestedInt64(live.Object, "status", "updatedReplicas")
			if err != nil {
				return false, err
			}
			if observed < live.GetGeneration() || ready != replicas || updated != replicas {
				return false, nil
			}
			if kind == "Deployment" {
				available, _, err := unstructured.NestedInt64(live.Object, "status", "availableReplicas")
				if err != nil {
					return false, err
				}
				if available != replicas {
					return false, nil
				}
			}
		}
		pending = nil
		return true, nil
	})
	return errors.Join(err, pending)
}
