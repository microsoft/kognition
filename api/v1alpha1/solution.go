package v1alpha1

import (
	"encoding/json"
	"time"
)

// Solution declares a high-level goal (L_intent) for the planner to decompose.
type Solution struct {
	TypeMeta   `json:",inline" yaml:",inline"`
	ObjectMeta `json:"metadata" yaml:"metadata"`
	Spec       SolutionSpec   `json:"spec" yaml:"spec"`
	Status     SolutionStatus `json:"status,omitempty" yaml:"status,omitempty"`
}

func (s *Solution) GetTypeMeta() TypeMeta      { return s.TypeMeta }
func (s *Solution) GetObjectMeta() *ObjectMeta { return &s.ObjectMeta }

// SolutionSpec defines the intent-level goal.
type SolutionSpec struct {
	// Goal is the natural-language description of the desired outcome.
	Goal string `json:"goal" yaml:"goal"`

	// Target optionally selects an existing Agent or Workflow to execute this
	// Solution's goal. When omitted, the planner generates its own pipeline.
	Target *SolutionTarget `json:"target,omitempty" yaml:"target,omitempty"`

	// Constraints are optional boundaries for the planner.
	Constraints []string `json:"constraints,omitempty" yaml:"constraints,omitempty"`

	// Preferences are optional key-value hints for the planner.
	Preferences map[string]string `json:"preferences,omitempty" yaml:"preferences,omitempty"`

	// Seed provides seedable determinism: same goal + model + seed = same plan.
	Seed *int64 `json:"seed,omitempty" yaml:"seed,omitempty"`

	// ModelRef optionally specifies the planner model to use.
	ModelRef *LocalObjectReference `json:"modelRef,omitempty" yaml:"modelRef,omitempty"`

	// Overrides allows per-Solution quota/policy overrides (validated against Workspace maxima).
	Overrides *SolutionOverrides `json:"overrides,omitempty" yaml:"overrides,omitempty"`

	// PromotionGates require successful EvaluationRuns before a new Solution
	// revision can become active.
	PromotionGates []SolutionPromotionGate `json:"promotionGates,omitempty" yaml:"promotionGates,omitempty"`
}

// SolutionPromotionGate references an Evaluation that must pass for the
// candidate Solution revision.
type SolutionPromotionGate struct {
	EvaluationRef LocalObjectReference `json:"evaluationRef" yaml:"evaluationRef"`
}

// SolutionTarget identifies an existing workload or AgentService that executes a Solution.
type SolutionTarget struct {
	// Kind is the target resource kind: Agent, AgentService, or Workflow.
	Kind string `json:"kind" yaml:"kind"`

	// Ref names the target in the Solution's namespace.
	Ref LocalObjectReference `json:"ref" yaml:"ref"`
}

// SolutionOverrides defines per-Solution quota and policy overrides.
type SolutionOverrides struct {
	// TokenBudget overrides the workspace-level token budget for this Solution.
	TokenBudget *TokenBudget `json:"tokenBudget,omitempty" yaml:"tokenBudget,omitempty"`

	// Hard overrides workspace-level hard quota limits for this Solution.
	Hard map[string]int64 `json:"hard,omitempty" yaml:"hard,omitempty"`
}

// SolutionStatus describes the observed state of a Solution.
type SolutionStatus struct {
	Phase      Phase       `json:"phase,omitempty" yaml:"phase,omitempty"`
	Conditions []Condition `json:"conditions,omitempty" yaml:"conditions,omitempty"`

	// ActiveRevision is the currently deployed revision number.
	ActiveRevision int64 `json:"activeRevision,omitempty" yaml:"activeRevision,omitempty"`

	// CandidateRevision is the compiled revision awaiting evaluation gates.
	CandidateRevision int64 `json:"candidateRevision,omitempty" yaml:"candidateRevision,omitempty"`

	// CompiledResources lists the resources generated by the planner for the active revision.
	CompiledResources []CompiledResource `json:"compiledResources,omitempty" yaml:"compiledResources,omitempty"`

	// GeneratedResources is kept for backward compatibility.
	GeneratedResources []GeneratedResource `json:"generatedResources,omitempty" yaml:"generatedResources,omitempty"`
}

// CompiledResource references a resource compiled by the planner, including its full manifest.
type CompiledResource struct {
	Kind      string          `json:"kind" yaml:"kind"`
	Name      string          `json:"name" yaml:"name"`
	Namespace string          `json:"namespace,omitempty" yaml:"namespace,omitempty"`
	Manifest  json.RawMessage `json:"manifest" yaml:"manifest"`
}

// GeneratedResource references a resource generated by the planner.
type GeneratedResource struct {
	Kind string `json:"kind" yaml:"kind"`
	Name string `json:"name" yaml:"name"`
}

// AgentAutoscaler defines autoscaling rules for agent instances.
type AgentAutoscaler struct {
	TypeMeta   `json:",inline" yaml:",inline"`
	ObjectMeta `json:"metadata" yaml:"metadata"`
	Spec       AgentAutoscalerSpec   `json:"spec" yaml:"spec"`
	Status     AgentAutoscalerStatus `json:"status,omitempty" yaml:"status,omitempty"`
}

func (a *AgentAutoscaler) GetTypeMeta() TypeMeta      { return a.TypeMeta }
func (a *AgentAutoscaler) GetObjectMeta() *ObjectMeta { return &a.ObjectMeta }

// AgentAutoscalerSpec defines autoscaling configuration.
type AgentAutoscalerSpec struct {
	// AgentRef references the Agent to scale.
	AgentRef LocalObjectReference `json:"agentRef" yaml:"agentRef"`

	// MinReplicas is the minimum instance count.
	MinReplicas int32 `json:"minReplicas" yaml:"minReplicas"`

	// MaxReplicas is the maximum instance count.
	MaxReplicas int32 `json:"maxReplicas" yaml:"maxReplicas"`

	// Metrics defines the scaling metrics and their targets.
	Metrics []AutoscalerMetric `json:"metrics" yaml:"metrics"`

	// ScaleUpPolicy configures scale-up behavior.
	ScaleUpPolicy *ScalingPolicy `json:"scaleUpPolicy,omitempty" yaml:"scaleUpPolicy,omitempty"`

	// ScaleDownPolicy configures scale-down behavior.
	ScaleDownPolicy *ScalingPolicy `json:"scaleDownPolicy,omitempty" yaml:"scaleDownPolicy,omitempty"`
}

// MetricType identifies a scaling metric.
type MetricType string

const (
	MetricQueueDepth MetricType = "QueueDepth"
	MetricP95Latency MetricType = "P95Latency"
)

// AutoscalerMetric defines a single metric and its target value.
type AutoscalerMetric struct {
	// Type is the metric identifier.
	Type MetricType `json:"type" yaml:"type"`

	// TargetValue is the threshold that triggers scaling.
	TargetValue int64 `json:"targetValue" yaml:"targetValue"`
}

// ScalingPolicy configures stabilization behavior for scaling decisions.
type ScalingPolicy struct {
	// StabilizationWindowSeconds is the time to wait after the last scale
	// event before another scale in the same direction is allowed.
	StabilizationWindowSeconds int32 `json:"stabilizationWindowSeconds" yaml:"stabilizationWindowSeconds"`
}

// AgentAutoscalerStatus describes the current autoscaling state.
type AgentAutoscalerStatus struct {
	CurrentReplicas int32       `json:"currentReplicas,omitempty" yaml:"currentReplicas,omitempty"`
	DesiredReplicas int32       `json:"desiredReplicas,omitempty" yaml:"desiredReplicas,omitempty"`
	LastScaleTime   *time.Time  `json:"lastScaleTime,omitempty" yaml:"lastScaleTime,omitempty"`
	Conditions      []Condition `json:"conditions,omitempty" yaml:"conditions,omitempty"`
}

// ModelAutoscaler defines vertical model-tier scaling rules for an agent.
type ModelAutoscaler struct {
	TypeMeta   `json:",inline" yaml:",inline"`
	ObjectMeta `json:"metadata" yaml:"metadata"`
	Spec       ModelAutoscalerSpec   `json:"spec" yaml:"spec"`
	Status     ModelAutoscalerStatus `json:"status,omitempty" yaml:"status,omitempty"`
}

func (m *ModelAutoscaler) GetTypeMeta() TypeMeta      { return m.TypeMeta }
func (m *ModelAutoscaler) GetObjectMeta() *ObjectMeta { return &m.ObjectMeta }

// ModelAutoscalerSpec defines fallback and recovery behavior for model-tier scaling.
type ModelAutoscalerSpec struct {
	// AgentRef references the Agent whose modelRef may be adjusted.
	AgentRef LocalObjectReference `json:"agentRef" yaml:"agentRef"`

	// PreferredModelRef is the primary Model the agent should use when healthy.
	PreferredModelRef LocalObjectReference `json:"preferredModelRef" yaml:"preferredModelRef"`

	// StabilizationWindowSeconds is the minimum time between model switches.
	StabilizationWindowSeconds int32 `json:"stabilizationWindowSeconds,omitempty" yaml:"stabilizationWindowSeconds,omitempty"`
}

// ModelAutoscalerStatus describes the current vertical scaling state.
type ModelAutoscalerStatus struct {
	CurrentModelRef string      `json:"currentModelRef,omitempty" yaml:"currentModelRef,omitempty"`
	DesiredModelRef string      `json:"desiredModelRef,omitempty" yaml:"desiredModelRef,omitempty"`
	LastScaleTime   *time.Time  `json:"lastScaleTime,omitempty" yaml:"lastScaleTime,omitempty"`
	Conditions      []Condition `json:"conditions,omitempty" yaml:"conditions,omitempty"`
}
