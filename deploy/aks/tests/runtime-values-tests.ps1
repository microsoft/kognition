#Requires -Version 7.0
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$generator = Join-Path $PSScriptRoot '../New-RuntimeValues.ps1'
$chart = Join-Path $PSScriptRoot '../../helm/kognition'

function Assert-True([bool]$Condition, [string]$Message) {
    if (-not $Condition) { throw $Message }
}

$json = & $generator -ImageRegistry demotest.azurecr.io -ImageTag build-123
$values = $json | ConvertFrom-Json -AsHashtable
Assert-True ($values.mode -eq 'kubernetes') 'Runtime base must be Kubernetes-only'
Assert-True ($values.memoryService.backendType -eq 'pgvector') 'Memory must persist in PostgreSQL'
Assert-True (-not $values.kbPgvector.enabled) 'Demo base must not create a second database'
Assert-True ($values.kbIngester.enabled) 'KnowledgeBase ingestion must do real work'
Assert-True ($values.postgres.auth.existingSecret -eq 'kognition-database') 'Database Secret matches bootstrap'
Assert-True ($values.runtimeAuth.existingSecret -eq 'kognition-runtime-auth') 'Runtime Secret matches bootstrap'
Assert-True (-not $values.runtimeAuth.create) 'Runtime credentials must not be regenerated by Helm'
Assert-True (-not $values.ingress.enabled) 'No public application ingress'
Assert-True ($values.global.thirdPartyImageRegistry -eq 'demotest.azurecr.io') 'Production third-party images use the verified private registry'
Assert-True ($values.global.aksAdmissionsEnforcerOptOut -eq $true) 'AKS runtime values stop the Admissions Enforcer from rewriting reviewed webhook selectors'

$valuesPath = [IO.Path]::GetTempFileName()
try {
    $json | Set-Content $valuesPath
    $rendered = & helm template kognition $chart --namespace kognition-system --kube-version 1.30.3 -f $valuesPath
    if ($LASTEXITCODE -ne 0) { throw 'Demo runtime Helm rendering failed.' }
    $manifest = $rendered -join "`n"
    foreach ($repository in @('kognition-k8s-controller', 'kognition-memory-service', 'kognition-memory-policy-gateway', 'kognition-tool-gateway', 'kognition-model-gateway', 'kognition-agent-communication-gateway', 'kognition-intent-gateway', 'kognition-kb-ingester', 'kognition-agent-runtime')) {
        Assert-True ($manifest.Contains("demotest.azurecr.io/${repository}:build-123")) "Image must be versioned and registry-qualified: $repository"
    }
    Assert-True ($manifest.Contains('demotest.azurecr.io/third-party/pgvector@sha256:ccc6e83d6e35e931dc7c5def2022729d5a6c370318d099181995567ff1fb4d6b')) 'PostgreSQL uses its verified digest-pinned private mirror'
    Assert-True ($manifest.Contains('demotest.azurecr.io/third-party/busybox@sha256:73aaf090f3d85aa34ee199857f03fa3a95c8ede2ffd4cc2cdb5b94e566b11662')) 'Wait containers use their verified digest-pinned private mirror'
    Assert-True ([regex]::Matches($manifest, '(?m)^kind: StatefulSet$').Count -eq 1) 'One bundled PostgreSQL instance'
    Assert-True ($manifest.Contains('storageClassName: "managed-csi"')) 'PostgreSQL uses an AKS managed disk'
    Assert-True ($manifest -match '(?m)^  name: \S+-migrations-[0-9a-f]{12}$') 'Kubernetes-mode migrations are a content-addressed ordinary Job'
    Assert-True (-not $manifest.Contains('post-install,post-upgrade')) 'Kubernetes-mode migrations are not Helm hooks'
    Assert-True ($manifest -notmatch 'postgres://') 'Database DSN is never embedded in Helm manifests'
    Assert-True ($manifest -notmatch '(?m)^kind: Ingress$|type: LoadBalancer') 'Runtime has no public ingress or load balancer'
    Assert-True ($manifest -notmatch 'nvidia.com/gpu') 'Runtime base must not request GPUs'
} finally {
    Remove-Item $valuesPath -ErrorAction SilentlyContinue
}
foreach ($tag in @('latest', 'dev', 'main')) {
    $rejected = $false
    try { & $generator -ImageRegistry demotest.azurecr.io -ImageTag $tag | Out-Null } catch { $rejected = $true }
    Assert-True $rejected "Unversioned tag must fail: $tag"
}

$groupId = '5f0d8020-43bd-44ba-ab94-edc228dfe551'
$withGroup = & $generator -ImageRegistry demotest.azurecr.io -ImageTag build-123 -Namespace demo-system -ReleaseFullname demo -WorkflowBindingAdminGroupId $groupId
$workflow = ($withGroup | ConvertFrom-Json -AsHashtable).k8sController.workflowExecutor
Assert-True ($workflow.enabled -eq $true) 'A supplied admin group enables the native workflow executor'
Assert-True ($workflow.bindingAdminGroups.Count -eq 1 -and $workflow.bindingAdminGroups[0] -eq $groupId) 'The Entra group object ID is the only binding administrator'
Assert-True ($workflow.principals[0].subject -eq 'system:serviceaccount:demo-system:demo-controller') 'The principal is the controller ServiceAccount of the selected release'
Assert-True (-not ($values.k8sController.ContainsKey('workflowExecutor'))) 'Workflow executor stays disabled without an admin group'
$groupPath = [IO.Path]::GetTempFileName()
try {
    $withGroup | Set-Content $groupPath
    $groupManifest = & helm template demo $chart --namespace demo-system --kube-version 1.30.3 -f $groupPath
    if ($LASTEXITCODE -ne 0) { throw 'Workflow executor Helm rendering failed.' }
    Assert-True (($groupManifest -join "`n").Contains($groupId)) 'The rendered controller must receive the binding administrator group'
} finally {
    Remove-Item $groupPath -ErrorAction SilentlyContinue
}
$collab = (& $generator -ImageRegistry demotest.azurecr.io -ImageTag build-123 -WorkflowBindingAdminGroupId $groupId -EnableWorkflowCollaboration | ConvertFrom-Json -AsHashtable).k8sController.workflowExecutor
Assert-True ($collab.collaboration.enabled -eq $true) 'The collaboration switch enables the chart collaboration flag'
Assert-True (-not $workflow.ContainsKey('collaboration')) 'Collaboration stays disabled unless requested'
$rejected = $false
try { & $generator -ImageRegistry demotest.azurecr.io -ImageTag build-123 -EnableWorkflowCollaboration | Out-Null } catch { $rejected = $true }
Assert-True $rejected 'Collaboration without the Workflow executor must be rejected'
$rejected = $false
try { & $generator -ImageRegistry demotest.azurecr.io -ImageTag build-123 -WorkflowBindingAdminGroupId ([guid]::Empty) | Out-Null } catch { $rejected = $true }
Assert-True $rejected 'The empty GUID must not be accepted as an administrator group'
Write-Output 'PASS: Kubernetes runtime base, single persistent database, existing credentials, versioned registry images, gateways, ingestion and no GPU/public ingress'